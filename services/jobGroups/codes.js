const autoName = (official) => official.replace(/\s*\([^)]*\)/g, '').replace(/ 및 /g, '·').trim();

const isGroupCode = (code) => typeof code === 'string' && code.length === 3 && code in TREE.names;

/** 직무 코드 → { code, name(화면), fullName(공식), top(대분류 2자리) }. 없는 코드면 null */
function groupInfo(code) {
  if (!isGroupCode(code)) return null;
  return { code, name: NAMES[code] ?? autoName(TREE.names[code]), fullName: TREE.names[code], top: TREE.parent[code] ?? null };
}

/** 우리 직업 → 트리에 있는 세분류 코드. keco+'00' 이 트리에 없으면 같은 앞 4자리의 첫 세분류(19개 직업) */
function occupationCodeOf(job) {
  const k = String(job?.work24?.keco?.code ?? '');
  if (!/^\d{4}$/.test(k)) return null;
  if (TREE.parent[`${k}00`]) return `${k}00`;
  return SIX.find((c) => c.startsWith(k) && TREE.parent[c]) ?? null;
}

/** 우리 직업 → 직무 코드(3자리). 연결이 없으면 null */
function groupOf(job) {
  if (JOB_OVERRIDE[job?.jobCode]) return JOB_OVERRIDE[job.jobCode];
  const occ = occupationCodeOf(job);
  return occ ? (PARENT_OVERRIDE[occ] ?? TREE.parent[occ] ?? null) : null;
}

module.exports = { TREE, PARENT_OVERRIDE, JOB_OVERRIDE, groupInfo, groupOf, occupationCodeOf, isGroupCode };
